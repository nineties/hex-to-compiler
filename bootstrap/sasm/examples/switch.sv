(include "std.sv")

(def A 3)
(def B 4)

(fun dense (n)
    (switch n
        (0 (return 10))
        (1 (return 11))
        (A (return 13))
        (default (return 99))
        )
    )

(fun sparse (n)
    (var r 0)
    (switch n
        (2 (= r 2))
        (B (= r 4))
        (1000 (= r 1000))
        (-5 (= r 5))
        )
    (return r)
    )

(fun check (name got want)
    (if (!= got want) (do
        (puts name)
        (puts " failed\n")
        (syscall 1 1)
        ))
    )

(fun main ()
    (check "dense0" (dense 0) 10)
    (check "dense1" (dense 1) 11)
    (check "dense2" (dense 2) 99)
    (check "dense3" (dense 3) 13)
    (check "dense4" (dense 4) 99)
    (check "dense-1" (dense -1) 99)
    (check "sparse2" (sparse 2) 2)
    (check "sparse3" (sparse 3) 0)
    (check "sparse4" (sparse 4) 4)
    (check "sparse1000" (sparse 1000) 1000)
    (check "sparse-5" (sparse -5) 5)
    (check "sparse999" (sparse 999) 0)
    (check "sparse-6" (sparse -6) 0)
    (check "sparse2000" (sparse 2000) 0)
    (puts "switch ok\n")
    )
